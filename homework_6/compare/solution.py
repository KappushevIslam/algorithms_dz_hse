"""Задача. Сравнение рекурсивной сортировки слиянием и рекурсивной быстрой
сортировки с замером времени работы на одном входе.

Идея. Шаг 1 делит список пополам до отрезков длины один и сливает
отсортированные половины двумя указателями. Шаг 2 выбирает последний элемент
опорным, выполняет разбиение Ломуто и обрабатывает меньшую часть рекурсией,
большую часть циклом. Шаг 3 возвращает новый список, замер времени выполняет
декоратор разностью показаний счетчика.

Структуры. Списки хранят вход, выход и копии отрезков, срезы выделяют
половины. Последний элемент выбран опорным для воспроизводимости квадратичного
числа сравнений на отсортированном входе. Рекурсия в меньшую часть удерживает
глубину стека в логарифмических пределах при сохранении квадратичного счета
сравнений. Декоратор сохраняет имя через functools.wraps для подмены вызова
без потери имени.
"""
# Сложность времени: merge_sort O(n log n) во всех случаях. quick_sort O(n log n) в среднем, O(n^2) на отсортированном входе.
# Сложность памяти: merge_sort O(n) под слияние плюс O(log n) под стек. quick_sort O(log n) под стек за счет цикла по большей части.
# Обоснование: слияние делит интервал пополам на глубине log n и сливает каждый уровень за O(n).
# Разбиение Ломуто сканирует отрезок линейно, на отсортированном входе дает пустую часть и отрезок короче на единицу, сумма длин дает O(n^2).
# Рекурсия в меньшую часть держит глубину O(log n).
# Качество: слияние устойчиво и требует O(n) дополнительной памяти. Быстрая сортировка неустойчива и работает на копии входа со стеком O(log n).
import functools
import time
from collections.abc import Callable
from typing import Any


def merge_sort(data: list[int]) -> list[int]:
    # отрезок длины ноль или один уже отсортирован
    if len(data) <= 1:
        return list(data)
    # середина делит список на равные половины
    mid = len(data) // 2
    left = merge_sort(data[:mid])
    right = merge_sort(data[mid:])
    # слияние проходит обе половины двумя указателями
    i = 0
    j = 0
    merged: list[int] = []
    # цикл выбирает меньший из текущих голов
    while i < len(left) and j < len(right):
        if left[i] <= right[j]:
            merged.append(left[i])
            i += 1
        else:
            merged.append(right[j])
            j += 1
    # остаток одной половины дописывается целиком
    merged.extend(left[i:])
    merged.extend(right[j:])
    return merged


def _partition(a: list[int], lo: int, hi: int) -> int:
    # опорный элемент берется последним элементом отрезка
    pivot = a[hi]
    # i отделяет элементы строго меньше опорного
    i = lo
    for j in range(lo, hi):
        # элемент меньше опорного меняется местами с границей
        if a[j] < pivot:
            a[i], a[j] = a[j], a[i]
            i += 1
    # опорный ставится сразу после меньшей части
    a[i], a[hi] = a[hi], a[i]
    return i


def _sort_range(a: list[int], lo: int, hi: int) -> None:
    # цикл оставляет большую часть для следующей итерации
    while lo < hi:
        # разбиение возвращает финальную позицию опорного
        p = _partition(a, lo, hi)
        # рекурсия обрабатывает меньшую часть
        if p - lo < hi - p:
            _sort_range(a, lo, p - 1)
            lo = p + 1
        else:
            _sort_range(a, p + 1, hi)
            hi = p - 1


def quick_sort(data: list[int]) -> list[int]:
    # копия сохраняет вход без изменений
    a = list(data)
    # сортировка идет на копии в отрезке от начала до конца
    _sort_range(a, 0, len(a) - 1)
    return a


def timing(fn: Callable[..., Any]) -> Callable[..., Any]:
    # обертка сохраняет имя исходной функции
    @functools.wraps(fn)
    def wrapper(*args: Any, **kwargs: Any) -> Any:
        # старт фиксируется до вызова
        start = time.perf_counter()
        result = fn(*args, **kwargs)
        # длительность равна разности показаний после вызова
        elapsed = time.perf_counter() - start
        print(f"{fn.__name__}: {elapsed:.6f} s")
        return result
    return wrapper


if __name__ == "__main__":
    demo = [9, 3, 7, 1, 8, 2, 5, 4, 6, 0]
    print(timing(merge_sort)(demo))
    print(timing(quick_sort)(demo))
