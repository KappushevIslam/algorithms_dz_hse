"""Задача. Отсортировать список целых чисел по возрастанию двумя итеративными методами.
Функции принимают список и возвращают новый отсортированный список.

Идея. Шаг 1 копирует вход для сохранения исходного порядка. Шаг 2 в merge_sort
удваивает ширину и сливает соседние отрезки в рабочий массив. Шаг 3 в quick_sort
хранит пары границ в явном стеке и делит отрезок схемой Ломуто с опорным последним элементом.

Структуры. Список хранит копию входа и рабочий массив. Стек списком хранит пары
lo hi и заменяет рекурсивные вызовы, глубина стека отражает вложенность отрезков.
Удвоение ширины заменяет рекурсивное деление пополам, проход по отрезкам использует
прямой доступ по индексу. Копии возвращаются для сохранения входа без изменений.
"""
# Сложность времени: merge_sort O(n log n) во всех случаях, quick_sort O(n log n) в среднем и O(n^2) в худшем случае.
# Сложность памяти: O(n) под копию входа и рабочий массив, стек границ требует O(log n) в среднем.
# Обоснование: merge_sort выполняет log n проходов удвоением ширины, каждый проход сливает n элементов.
# Каждый проход quick_sort сканирует отрезок разбиением, суммарное число сравнений зависит от глубины деления.
# Качество: явный стек хранит O(log n) пар в среднем и O(n) в худшем случае, восходящий вариант держит один вспомогательный массив длины n.


def _lomuto_partition(a: list[int], lo: int, hi: int) -> int:
    # опорный элемент фиксируется как последний элемент отрезка
    pivot = a[hi]
    # счетчик i хранит границу меньших элементов
    i = lo
    # проход сравнивает каждый элемент отрезка с опорным
    for j in range(lo, hi):
        # элемент меньший или равный опорному перемещается влево
        if a[j] <= pivot:
            a[i], a[j] = a[j], a[i]
            i += 1
    # опорный элемент ставится на итоговую позицию
    a[i], a[hi] = a[hi], a[i]
    return i


def merge_sort(data: list[int]) -> list[int]:
    # копия входа сохраняет исходный порядок
    src = list(data)
    n = len(src)
    # отрезок длины 0 или 1 уже отсортирован
    if n <= 1:
        return src
    # рабочий массив принимает результат каждого прохода
    dst: list[int] = [0] * n
    # ширина отрезка удваивается после каждого прохода
    width = 1
    # цикл продолжается пока ширина покрывает весь массив
    while width < n:
        # проход сливает соседние пары отрезков ширины width
        for lo in range(0, n, 2 * width):
            # границы отрезков фиксируют инвариант слияния
            mid = min(lo + width, n)
            hi = min(lo + 2 * width, n)
            i = lo
            j = mid
            k = lo
            # слияние выбирает меньший головной элемент
            while i < mid and j < hi:
                if src[i] <= src[j]:
                    dst[k] = src[i]
                    i += 1
                else:
                    dst[k] = src[j]
                    j += 1
                k += 1
            # остаток левого отрезка дописывается без сравнений
            while i < mid:
                dst[k] = src[i]
                i += 1
                k += 1
            # остаток правого отрезка дописывается без сравнений
            while j < hi:
                dst[k] = src[j]
                j += 1
                k += 1
        # готовый проход становится входом следующего прохода
        src, dst = dst, src
        width *= 2
    return src


def quick_sort(data: list[int]) -> list[int]:
    # копия входа сохраняет исходный порядок
    a = list(data)
    n = len(a)
    # отрезок длины 0 или 1 уже отсортирован
    if n <= 1:
        return a
    # стек хранит пары границ отложенных отрезков
    stack: list[tuple[int, int]] = [(0, n - 1)]
    # цикл продолжается пока стек содержит границы
    while stack:
        lo, hi = stack.pop()
        # отрезок длины 0 или 1 пропускается
        if lo >= hi:
            continue
        # разбиение ставит опорный элемент на итоговую позицию
        p = _lomuto_partition(a, lo, hi)
        # левый отрезок откладывается в стек для поздней обработки
        stack.append((lo, p - 1))
        # правый отрезок откладывается в стек для поздней обработки
        stack.append((p + 1, hi))
    return a


