"""Задача. Дан список целых чисел nums и номер k, k 1 означает максимум.
Требуется вернуть k-й по величине элемент без изменения входа.

Идея. Шаг 1 проверяет границы k и копирует массив. Шаг 2 выбирает пивот
из середины текущего отрезка. Шаг 3 делит отрезок на три группы флагом.
Шаг 4 отбрасывает часть без ответа и сужает отрезок циклом.

Структуры. Копия списка хранит рабочее состояние. Индексы lo и hi хранят
границы текущего отрезка. Трехстороннее разделение собирает равные пивоту
за один проход и снимает вырождение на дубликатах. Пивот из середины делит
отрезок примерно пополам на упорядоченных данных. Цикл вместо рекурсии держит
стек постоянным.
Копия входа сохраняет исходный порядок. ValueError сигнализирует пустой
вход и k вне отрезка 1 len(nums).
"""
# Сложность времени: O(n) в среднем, O(n^2) в худшем случае.
# Сложность памяти: O(n) под копию массива, O(1) дополнительно.
# Обоснование: каждый проход сканирует текущий отрезок линейно. Размер отрезка
# убывает при удачном пивоте, цикл исключает стек рекурсии.
# Качество: ожидаемое время O(n), худший случай O(n^2) при вырожденных сериях пивотов, трехстороннее разделение убирает дубликаты за один проход.


def find_kth_largest(nums: list[int], k: int) -> int:
    # проверка границ выполняется до копирования для раннего отказа
    if not nums or k < 1 or k > len(nums):
        raise ValueError("k вне допустимого диапазона")
    # копия защищает входной список от изменений
    a = list(nums)
    # инвариант: ответ находится внутри отрезка lo hi
    lo = 0
    hi = len(a) - 1
    while True:
        # пивот из середины делит упорядоченный отрезок примерно пополам
        pivot = a[(lo + hi) // 2]
        # трехстороннее разделение: меньше, равно, больше
        lt = lo
        i = lo
        gt = hi
        while i <= gt:
            # элемент меньше пивота уходит в левую часть
            if a[i] < pivot:
                a[lt], a[i] = a[i], a[lt]
                lt += 1
                i += 1
            # элемент больше пивота уходит в правую часть
            elif a[i] > pivot:
                a[i], a[gt] = a[gt], a[i]
                gt -= 1
            else:
                i += 1
        # подсчет правой части определяет положение k относительно пивота
        greater = hi - gt
        equal = gt - lt + 1
        # k внутри правой части: левая часть и группа равных отброшены
        if k <= greater:
            lo = gt + 1
        # k внутри группы равных: пивот фиксирует ответ
        elif k <= greater + equal:
            return pivot
        # k внутри левой части: правая часть и группа равных отброшены
        else:
            k -= greater + equal
            hi = lt - 1


if __name__ == "__main__":
    print(find_kth_largest([3, 2, 1, 5, 6, 4], 2))
    print(find_kth_largest([3, 2, 3, 1, 2, 4, 5, 5, 6], 4))
