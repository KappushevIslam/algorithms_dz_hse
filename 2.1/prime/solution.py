"""Задача. Найти количество простых чисел строго меньше N.

Идея. Шаг 1 строит таблицу меток для чисел от 0 до N минус 1. Шаг 2
вычеркивает кратные каждого простого до корня из N. Шаг 3 считает
оставшиеся метки.

Структуры. Используется список логических меток длиной N. Список дает
прямой доступ по индексу. Выбор объясняется простотой вычеркивания.
"""
# Сложность времени: O(n log log n), где n значение входа N.
# Сложность памяти: O(n) под таблицу меток.
# Обоснование: каждое составное число вычеркивается по числу его простых
# делителей. Суммарная работа описывается оценкой решета Эратосфена.


def count_primes(n: int) -> int:
    # для N меньше либо равно 2 простых чисел в диапазоне нет
    if n <= 2:
        return 0
    # метка True означает гипотезу о простоте индекса
    is_prime = [True] * n
    is_prime[0] = False
    is_prime[1] = False
    # достаточно обработать делители до корня из n
    limit = int(n ** 0.5) + 1
    for p in range(2, limit):
        # составные p уже вычеркнуты и пропускаются
        if is_prime[p]:
            # первое невычеркнутое кратное равно p умножить на p
            start = p * p
            # вычеркивание кратных с шагом p
            for multiple in range(start, n, p):
                is_prime[multiple] = False
    # подсчет уцелевших меток
    total = 0
    for flag in is_prime:
        if flag:
            total += 1
    return total


if __name__ == "__main__":
    print(count_primes(10))
    print(count_primes(1))

