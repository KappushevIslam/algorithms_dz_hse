"""Задача. Проверить целое положительное число на палиндром без строк.

Идея. Шаг 1 отсекает заведомо неподходящие числа. Шаг 2 разворачивает
правую половину числа. Шаг 3 сравнивает развернутую половину с левой частью.

Структуры. Используются только целые переменные. Дополнительные массивы
не требуются. Выбор объясняется постоянным расходом памяти.
"""
# Сложность времени: O(d), где d число десятичных цифр входа.
# Сложность памяти: O(1), хранятся только две целые переменные.
# Обоснование: цикл выполняет d // 2 итераций. Каждая итерация делает
# постоянное число арифметических операций.


def is_palindrome(x: int) -> bool:
    # отсечение отрицательных чисел
    if x < 0:
        return False
    # отсечение чисел с нулем на конце, кроме самого нуля
    if x % 10 == 0 and x != 0:
        return False
    # rev хранит развернутую правую половину
    rev = 0
    # цикл переносит цифры справа налево до середины
    while x > rev:
        rev = rev * 10 + x % 10
        x //= 10
    # при четной длине половины равны
    # при нечетной длине средняя цифра остается в rev и отбрасывается делением
    return x == rev or x == rev // 10


if __name__ == "__main__":
    print(is_palindrome(121))
    print(is_palindrome(31))

# Визуализация. Пример 121.
# Шаг 1. x 121 rev 0. Перенос цифры 1. Стало x 12 rev 1.
# Шаг 2. x 12 rev 1. Перенос цифры 2. Стало x 1 rev 12.
# Шаг 3. Условие x больше rev ложно. Проверка x равно rev без средней цифры.
# Итог. 1 равно 1. Ответ True.
