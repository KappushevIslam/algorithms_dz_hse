"""Задача. Найти максимальную сумму подмножества, которая делится на 2.

Идея. Шаг 1 считает сумму всех элементов. Шаг 2 возвращает сумму, если
она четная. Шаг 3 вычитает минимальное нечетное число, если сумма нечетная.

Структуры. Используются два целых счетчика. Массив для хранения не нужен
сверх входа. Выбор объясняется линейным проходом без сортировки.
"""
# Сложность времени: O(n), где n длина массива.
# Сложность памяти: O(1), хранятся только сумма и минимум.
# Обоснование: первый проход считает сумму. Второй проход ищет минимальное
# нечетное. Оба прохода линейные. Дополнительные структуры не создаются.


def max_even_sum(data: list[int]) -> int:
    # total хранит сумму всех элементов
    total = 0
    for value in data:
        total += value
    # четная сумма уже является ответом, так как все числа положительные
    if total % 2 == 0:
        return total
    # поиск минимального нечетного для вычитания
    min_odd: int | None = None
    for value in data:
        # проверка нечетности остатком от деления
        if value % 2 == 1:
            if min_odd is None or value < min_odd:
                min_odd = value
    # защита от пустого входа и четного нуля
    if min_odd is None:
        return 0
    # вычитание минимального нечетного дает максимальную четную сумму
    return total - min_odd


if __name__ == "__main__":
    print(max_even_sum([5, 7, 13, 2, 14]))
    print(max_even_sum([3]))

# Визуализация. Пример [5, 7, 13, 2, 14].
# Шаг 1. Накопление суммы. Стало 5. Стало 12. Стало 25. Стало 27. Стало 41.
# Шаг 2. Проверка четности. 41 нечетно. Ответ требует вычитания.
# Шаг 3. Просмотр нечетных. Кандидаты 5 7 13. Минимум 5.
# Итог. 41 минус 5 равно 36. Ответ 36.
# Визуализация. Пример [3].
# Шаг 1. Сумма 3. Сумма нечетна.
# Шаг 2. Минимальное нечетное 3.
# Итог. 3 минус 3 равно 0. Ответ 0.
