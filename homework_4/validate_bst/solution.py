"""Задача. Проверить произвольное бинарное дерево на свойство BST.

Идея. Шаг 1 задает допустимый интервал для корня от минус до плюс бесконечности.
Шаг 2 спускается рекурсивно и сужает интервал левому и правому потомкам.
Шаг 3 отвергает значение вне интервала и принимает дерево при полном проходе.

Структуры. Класс TreeNode хранит значение и ссылки left и right. Проверка несет
границы low и high вдоль пути от корня. Строгие неравенства повторяют определение BST.
Дубликаты считаются нарушением. Границы стартуют с бесконечности для int входов.
Класс продублирован между папками для самодостаточности ссылок Stepik.
"""
# Сложность времени: O(n) при полном проходе, ранний выход сокращает работу до O(k).
# Сложность памяти: O(h) под стек рекурсии, где h высота дерева.
# Обоснование: каждый узел посещается один раз. Глубина рекурсии равна длине пути от корня.
# Качество: интервальный метод держит O(h) памяти против O(n) у сбора inorder списка.
# Сложность времени: O(n) при полном проходе, ранний выход сокращает работу до O(k).
# Сложность памяти: O(h) под стек рекурсии, где h высота дерева.
# Обоснование: каждый узел посещается один раз. Глубина рекурсии равна длине пути от корня.


class TreeNode:
    def __init__(self, val: int, left: "TreeNode | None" = None, right: "TreeNode | None" = None):
        self.val = val
        self.left = left
        self.right = right


def is_valid_bst(root: "TreeNode | None") -> bool:
    # check несет допустимый интервал значений для поддерева
    def check(node: "TreeNode | None", low: float, high: float) -> bool:
        # пустая ветвь ограничений не нарушает
        if node is None:
            return True
        # значение обязано лежать строго внутри интервала
        if not (low < node.val < high):
            return False
        # левое поддерево наследует верхнюю границу от текущего узла
        # правое поддерево наследует нижнюю границу от текущего узла
        return check(node.left, low, node.val) and check(node.right, node.val, high)

    # корень стартует с бесконечным интервалом
    return check(root, float("-inf"), float("inf"))


if __name__ == "__main__":
    valid = TreeNode(5, TreeNode(3, TreeNode(2), TreeNode(4)), TreeNode(7, TreeNode(6), TreeNode(8)))
    broken = TreeNode(5, TreeNode(3, TreeNode(2), TreeNode(6)), TreeNode(7))
    print(is_valid_bst(valid))
    print(is_valid_bst(broken))

