# Шаг 1. Листья 2 4 6 8. Высота каждого равна 1.
# Шаг 2. Узлы 3 и 7. Высоты потомков 1 и 1. Расхождение 0. Высота каждого равна 2.
# Шаг 3. Узел 5. Высоты потомков 2 и 2. Расхождение 0. Высота равна 3. Ответ True.
# Шаг 4. Цепочка bad. Узел 4 высота 1. Узел 3 высоты 1 и 0. Расхождение 1.
# Шаг 5. Узел 2 высоты 2 и 0. Расхождение 2. Маркер минус 1. Ответ False.
# Итог. Первое дерево сбалансировано. Второе дерево отклонено на узле 2.
