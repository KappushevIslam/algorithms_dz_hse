"""Задача. Проверить сбалансированность бинарного дерева по высоте.

Идея. Шаг 1 считает высоту поддеревьев одним постфиксным проходом.
Шаг 2 сравнивает высоты левого и правого потомков в каждом узле.
Шаг 3 поднимает маркер минус 1 при расхождении больше 1 и гасит верхние уровни.

Структуры. Класс TreeNode хранит значение и ссылки left и right. Helper
возвращает высоту или маркер минус 1. Маркер выбран для остановки без исключений.
"""
# Сложность времени: O(n) во всех случаях, каждое поддерево считается один раз.
# Сложность памяти: O(h) под стек рекурсии, где h высота дерева.
# Обоснование: каждый узел посещается один раз. Глубина рекурсии равна длине пути от корня.


class TreeNode:
    def __init__(self, val: int, left: "TreeNode | None" = None, right: "TreeNode | None" = None):
        self.val = val
        self.left = left
        self.right = right


def is_balanced(root: "TreeNode | None") -> bool:
    # helper возвращает высоту поддерева или минус 1 при дисбалансе
    def height(node: "TreeNode | None") -> int:
        # пустая ветвь имеет высоту ноль
        if node is None:
            return 0
        # левая высота считается первой для раннего выхода
        left = height(node.left)
        # маркер слева гасит проверку текущего узла
        if left == -1:
            return -1
        # правая высота считается второй для раннего выхода
        right = height(node.right)
        # маркер справа гасит проверку текущего узла
        if right == -1:
            return -1
        # расхождение больше 1 фиксирует дисбаланс маркером
        if abs(left - right) > 1:
            return -1
        # высота узла равна максимуму потомков плюс сам узел
        return max(left, right) + 1

    # корень сбалансирован при отсутствии маркера
    return height(root) != -1


if __name__ == "__main__":
    good = TreeNode(5, TreeNode(3, TreeNode(2), TreeNode(4)), TreeNode(7, TreeNode(6), TreeNode(8)))
    bad = TreeNode(1, TreeNode(2, TreeNode(3, TreeNode(4))))
    print(is_balanced(good))
    print(is_balanced(bad))

