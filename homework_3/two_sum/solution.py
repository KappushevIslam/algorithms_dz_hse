"""Задача. Найти индексы двух элементов массива с суммой k.

Идея. Шаг 1 идет по массиву слева направо. Шаг 2 для каждого элемента
вычисляет дополнение до k. Шаг 3 возвращает пару при первом совпадении
дополнения с ранее встреченным значением.

Структуры. Словарь хранит значение и его индекс. Словарь дает проверку
наличия за O(1). Выбор объясняется линейным временем без вложенных циклов.
"""
# Сложность времени: O(n), где n длина массива.
# Сложность памяти: O(n) под словарь встреченных значений.
# Обоснование: проход по массиву одиночный. Каждая операция со словарем
# выполняется за O(1) в среднем.


def two_sum(arr: list[int], k: int) -> tuple[int, int]:
    # seen хранит значение и индекс первого вхождения
    seen: dict[int, int] = {}
    for i, value in enumerate(arr):
        # need дополняет текущее значение до k
        need = k - value
        # совпадение означает найденную пару
        if need in seen:
            first = seen[need]
            # ответ упорядочен по возрастанию индексов
            if first < i:
                return (first, i)
            return (i, first)
        seen[value] = i
    # пара гарантирована условием, ветвь недостижима на корректном входе
    raise ValueError("pair not found")


if __name__ == "__main__":
    print(two_sum([1, 3, 4, 10], 7))
    print(two_sum([5, 5, 1, 4], 10))

# Визуализация. Пример arr [1, 3, 4, 10] k 7.
# Шаг 1. i 0 value 1. need 6. Словарь пуст. Запись 1: 0.
# Шаг 2. i 1 value 3. need 4. Значения 4 в словаре нет. Запись 3: 1.
# Шаг 3. i 2 value 4. need 3. Значение 3 найдено с индексом 1.
# Итог. Ответ (1, 2). Проверка 3 плюс 4 равно 7.
# Визуализация. Пример arr [5, 5, 1, 4] k 10.
# Шаг 1. i 0 value 5. need 5. Словарь пуст. Запись 5: 0.
# Шаг 2. i 1 value 5. need 5. Значение 5 найдено с индексом 0.
# Итог. Ответ (0, 1). Проверка 5 плюс 5 равно 10.
