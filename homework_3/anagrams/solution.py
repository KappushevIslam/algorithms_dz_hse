"""Задача. Сгруппировать слова так, чтобы анаграммы попали в одну группу.

Идея. Шаг 1 строит ключ группы из отсортированных букв слова. Шаг 2
добавляет слово в список с этим ключом. Шаг 3 возвращает все списки групп.

Структуры. Словарь отображает ключ в список слов. Кортеж букв служит
ключом. Выбор объясняется линейным проходом по словам без попарных
сравнений.
"""
# Сложность времени: O(n * m log m), где n число слов, m длина слова.
# Сложность памяти: O(n * m) под словарь групп.
# Обоснование: каждое слово сортируется за m log m. Вставка в словарь
# выполняется за O(1) в среднем.


def group_anagrams(strs: list[str]) -> list[list[str]]:
    # groups хранит ключ из букв и список слов группы
    groups: dict[tuple[str, ...], list[str]] = {}
    for word in strs:
        # key одинаков для всех анаграмм одного набора букв
        key = tuple(sorted(word))
        if key in groups:
            groups[key].append(word)
        else:
            groups[key] = [word]
    return list(groups.values())


def normalize(groups: list[list[str]]) -> list[list[str]]:
    # сортировка внутри групп и между группами для сравнения
    return sorted([sorted(group) for group in groups])


if __name__ == "__main__":
    print(normalize(group_anagrams(["eat", "tea", "tan", "ate", "nat", "bat"])))

# Визуализация. Пример ["eat", "tea", "tan", "ate", "nat", "bat"].
# Шаг 1. Слово eat. Ключ (a, e, t). Новая группа. Группы [[eat]].
# Шаг 2. Слово tea. Ключ (a, e, t). Добавление в группу 0.
# Группы [[eat, tea]].
# Шаг 3. Слово tan. Ключ (a, n, t). Новая группа. Группы [[eat, tea], [tan]].
# Шаг 4. Слово ate. Ключ (a, e, t). Добавление в группу 0.
# Группы [[eat, tea, ate], [tan]].
# Шаг 5. Слово nat. Ключ (a, n, t). Добавление в группу 1.
# Группы [[eat, tea, ate], [tan, nat]].
# Шаг 6. Слово bat. Ключ (a, b, t). Новая группа.
# Итог. Группы [[eat, tea, ate], [tan, nat], [bat]]. Всего 3 группы.
