# Шаг 1. Push 1 2 3 без снятий. Стек [1, 2, 3].
# Шаг 2. Верх 3 совпал с popped 0. Pop. Pos 1. Стек [1, 2].
# Шаг 3. Верх 2 против popped 1 равного 1. Снятий больше нет.
# Итог. Pos 1 меньше длины popped. Ответ False.
