"""Задача. Проверить достижимость порядка pop на стеке для порядка push.

Идея. Шаг 1 кладет элементы pushed в стек по порядку. Шаг 2 снимает верх
стека при совпадении с очередным элементом popped. Шаг 3 сравнивает число
снятий с длиной popped.

Структуры. Используется список как стек. Целый указатель читает popped по
порядку. Выбор объясняется прямым моделированием операций push и pop.
"""
# Сложность времени: O(n), где n длина pushed.
# Сложность памяти: O(n) под стек в худшем случае.
# Обоснование: каждый элемент кладется в стек один раз и снимается один раз.


def validate(pushed: list[int], popped: list[int]) -> bool:
    # stack хранит элементы, ожидающие снятия
    stack: list[int] = []
    # pos указывает на очередной ожидаемый элемент popped
    pos = 0
    # каждый элемент pushed попадает в стек ровно один раз
    for value in pushed:
        stack.append(value)
        # инвариант: верх стека сравнивается с popped[pos]
        while stack and pos < len(popped) and stack[-1] == popped[pos]:
            stack.pop()
            pos += 1
    # порядок достижим, если сняты все элементы popped
    return pos == len(popped)


if __name__ == "__main__":
    print(validate([1, 2, 3, 4, 5], [1, 3, 5, 4, 2]))
    print(validate([1, 2, 3], [3, 1, 2]))

# Визуализация. Пример pushed [1, 2, 3, 4, 5] popped [1, 3, 5, 4, 2].
# Шаг 1. Push 1. Стек [1]. Верх совпал с popped 0. Pop. Pos 1. Стек [].
# Шаг 2. Push 2. Стек [2]. Верх 2 против popped 1 равного 3. Пауза.
# Шаг 3. Push 3. Стек [2, 3]. Верх совпал с popped 1. Pop. Pos 2. Стек [2].
# Шаг 4. Push 4. Стек [2, 4]. Верх 4 против popped 2 равного 5. Пауза.
# Шаг 5. Push 5. Стек [2, 4, 5]. Верх совпал с popped 2. Pop. Pos 3.
# Шаг 6. Верх 4 совпал с popped 3. Pop. Pos 4. Верх 2 совпал с popped 4.
# Pop. Pos 5. Стек [].
# Итог. Pos 5 равно длине popped. Ответ True.
